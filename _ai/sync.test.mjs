test('helpers get their AGENTS.md sections verbatim in every tool, with no chat-only wording', () => {
  const out = build('work');
  for (const f of readdirSync(join(ROOT, '_ai/agents')).filter((n) => n.endsWith('.md') && n !== '_core.md')) {
    const name = f.slice(0, -3);
    const { meta } = parse(readFileSync(join(ROOT, '_ai/agents', f), 'utf8').replace(/\r\n/g, '\n'));
    // floor: every helper gets the agent and secrets rules; one that runs commands also the database rules and hard stops
    const floor = ['Every agent', 'Secrets and data', ...(meta.tools.includes('execute') ? ['Databases', 'Hard stops'] : []),
      ...(['worker', 'reviewer'].includes(name) ? ['Code'] : [])];
    for (const s of floor) assert.ok(meta.sections.includes(s), `${name} lacks ${s}`);
    for (const text of [out[`.claude/agents/${name}.md`], JSON.parse(out[`.kiro/agents/${name}.json`]).prompt, out[`.github/agents/${name}.agent.md`]]) {
      // after a blank line, so the first heading does not join the body's last list item
      assert.ok(text.includes(`\n\n${sections(meta.sections)}`), name);
      assert.doesNotMatch(text, /this chat|the user names/i, name);
    }
  }
  const copilot = out['.github/copilot-instructions.md'];
  assert.ok(copilot.includes(`\n\n${sections(['Databases', 'Hard stops', 'Secrets and data'])}`));
  assert.doesNotMatch(copilot, /this chat|the user names/i);
  // independent oracle: a section is its heading line and every line up to the next `## ` heading
  const lines = readFileSync(join(ROOT, 'AGENTS.md'), 'utf8').replace(/\r\n/g, '\n').split('\n');
  const oracle = (name) => {
    const i = lines.indexOf(`## ${name}`);
    let j = i + 1;
    while (j < lines.length && !lines[j].startsWith('## ')) j++;
    return lines.slice(i, j).join('\n').trimEnd() + '\n';
  };
  for (const s of ['Every agent', 'Code', 'Databases', 'Hard stops', 'Secrets and data']) assert.equal(sections([s]), oracle(s), s);
  assert.match(sections(['Hard stops']), /`down -v`.*execute_site_tool.*executeDestructive/s);
  assert.match(sections(['Secrets and data']), /Never touch `personal\/`/);
  assert.throws(() => sections(['No such'], 'x.md'), /^Error: x\.md: AGENTS\.md has no section "No such"$/);
});

