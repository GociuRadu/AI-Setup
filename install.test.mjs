test('false in setup.json removes only that component; a tool turned off loses its files and settings', () => {
  const m = machine();
  m.run();
  const userFile = join(m.work, '.claude', 'skills', 'my-own', 'SKILL.md');
  put(userFile, 'mine');
  m.setSetup((s) => { s.skills.debate = false; s.agents.tester.on = false; });
  const r = m.run();
  assert.ok(r.changes.every((c) => /debate|tester|\.ai-device\.json/.test(c)), r.changes.join('\n'));
  for (const dir of ['.claude/skills', '.github/skills', '.kiro/skills']) assert.ok(!existsSync(join(m.work, dir, 'debate')), dir);
  assert.ok(!existsSync(join(m.work, '.claude/agents/tester.md')));
  assert.ok(existsSync(join(m.work, '.claude/skills/pplan/SKILL.md')) && existsSync(userFile));

  m.setSetup((s) => { s.tools.kiro = false; });
  m.run();
  assert.ok(!existsSync(join(m.work, '.kiro', 'skills')) && !existsSync(join(m.work, '.kiro', 'hooks', 'guard.json')));
  assert.doesNotMatch(read(m.home, '.kiro', 'settings', 'permissions.yaml'), /mdenc/);
});

test('Kiro rules are matched by content, so a rule Kiro rewrote in block style is not duplicated', () => {
  const rules = kiroRules({ work: 'C:/w', vault: 'C:/v', home: 'C:/h', temp: 'C:/t' });
  const first = mergeKiroPermissions('', { rules, managed: {}, vault: 'C:/v' });
  // Kiro saved the file: comments gone, one rule rewritten in block style
  const deny = rules.find((r) => r.capability === 'shell');
  const rewritten = first.replace(`  - ${JSON.stringify(deny)}`, ['  - capability: shell', '    match:', ...deny.match.map((x) => `      - "${x}"`), '    effect: deny'].join('\n'));
  assert.equal(parseKiroRules(rewritten).items.length, rules.length);
  const second = mergeKiroPermissions(rewritten, { rules, managed: { kiroRules: rules }, vault: 'C:/v' });
  assert.equal(second, first);
  assert.equal(mergeKiroPermissions('other: 1\n', { rules: [], managed: {}, vault: undefined }), 'other: 1\nrules:\n');
});

test('settings with comments are left alone, and a dry run writes nothing', () => {
  const m = machine();
  const commented = '{\n  // mine\n  "a": 1,\n}\n';
  put(join(m.vscodeUser, 'settings.json'), commented);
  const dry = m.run({ dryRun: true });
  assert.ok(dry.changes.length > 0);
  assert.ok(!existsSync(join(m.work, 'AGENTS.md')) && !existsSync(join(m.work, '.ai-device.json')));
  const r = m.run();
  assert.ok(r.warnings.some((w) => /comments or trailing commas/.test(w)));
  assert.equal(read(m.vscodeUser, 'settings.json'), commented);
});
