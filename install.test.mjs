import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, cpSync, readdirSync, symlinkSync, rmSync, realpathSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { install, loadSetup, frontmatter, parseKiroRules, mergeKiroPermissions, kiroRules, blankJsonc, editJsonc, REPO } from './install.mjs';

const read = (...p) => readFileSync(join(...p), 'utf8');
const readJson = (...p) => JSON.parse(read(...p));
const put = (file, text) => { mkdirSync(join(file, '..'), { recursive: true }); writeFileSync(file, text); };

// a copy of this repo (so setup.json can change) and a fake machine: home, VS Code user folder, vault, work folder
function machine() {
  // the real spelling: install.mjs reports paths as they are on disk, and a temp folder can be an 8.3 short name (RUNNER~1)
  const root = realpathSync.native(mkdtempSync(join(tmpdir(), 'ai-setup-')));
  const repo = join(root, 'repo');
  cpSync(REPO, repo, { recursive: true, filter: (src) => !/[\\/](\.git|node_modules)([\\/]|$)/.test(src) });
  const home = join(root, 'home'), vscodeUser = join(root, 'Code', 'User'), vault = join(root, 'vault'), work = join(root, 'work');
  for (const d of [join(home, '.claude'), join(home, '.kiro', 'settings'), vscodeUser, join(vault, '.obsidian'), join(work, 'Shop', 'code')]) mkdirSync(d, { recursive: true });
  const logs = [];
  const run = (extra = {}) => install({ repo, home, vscodeUser, work, vault, which: () => false, log: (l) => logs.push(l), ...extra });
  const setSetup = (change) => { const f = join(repo, 'setup.json'); const s = JSON.parse(read(f)); change(s); writeFileSync(f, JSON.stringify(s, null, 2)); };
  return { root, repo, home, vscodeUser, vault, work, run, logs, setSetup };
}

test('setup.json names exactly the components the repo has', () => {
  const s = loadSetup(REPO);
  assert.equal(Object.keys(s.skills).length, 11);
  assert.deepEqual(Object.keys(s.agents).sort(), ['challenger', 'researcher', 'reviewer', 'tester']);
  const m = machine();
  mkdirSync(join(m.repo, 'skills', 'extra'));
  assert.throws(() => loadSetup(m.repo), /setup.json skills: lists \[.*\] but the repo has \[.*extra.*\]/);
});

test('every skill fits the format: name = folder, a description up to 1,024 characters, a body under 500 lines', () => {
  for (const skill of Object.keys(loadSetup(REPO).skills)) {
    const { meta, body } = frontmatter(read(REPO, 'skills', skill, 'SKILL.md').replace(/\r\n/g, '\n'));
    assert.equal(meta.name, skill);
    assert.ok(meta.description && meta.description.length <= 1024, `${skill}: description length ${meta.description?.length}`);
    assert.ok(body.split('\n').length < 500, `${skill}: body has ${body.split('\n').length} lines`);
  }
});

test('a first install writes every tool format, merges user settings and keeps what is not ours', () => {
  const m = machine();
  // what a machine with the old setup has
  put(join(m.home, '.claude', 'settings.json'), JSON.stringify({ model: 'sonnet', outputStyle: 'Concise', theme: 'dark', permissions: { deny: ['Read(./secret/**)'] } }, null, 4));
  put(join(m.vscodeUser, 'settings.json'), JSON.stringify({ 'workbench.colorTheme': 'Dark+', 'chat.tools.terminal.autoApprove': { '/^npm test$/': true } }, null, 4));
  put(join(m.home, '.kiro', 'settings', 'permissions.yaml'), [
    'rules:', '  # >>> generated by node _ai/sync.mjs; add your own rules outside this block',
    `  - {"capability":"filesystem","match":["${m.vault.replace(/\\/g, '/')}/Personal/**"],"effect":"deny"}`, '  # <<< generated by node _ai/sync.mjs',
    '  - capability: shell', '    effect: allow', '    match:', '      - "*"', '',
  ].join('\n'));
  put(join(m.work, '.mcp.json'), JSON.stringify({ mcpServers: { github: { type: 'http', url: 'https://x' }, playwright: { type: 'stdio', command: 'npx' }, mlflow: { type: 'stdio', command: 'mlflow' } } }));
  put(join(m.work, '.vscode', 'mcp.json'), JSON.stringify({ servers: { github: { type: 'http', url: 'https://x' }, mine: { type: 'stdio', command: 'x' } } }));
  put(join(m.work, '.claude', 'settings.local.json'), JSON.stringify({ permissions: { allow: ['Edit', 'Bash'], defaultMode: 'bypassPermissions' } }));
  put(join(m.work, 'AGENTS.md'), '# my own rules\n');
  put(join(m.work, '.ai-device.json'), JSON.stringify({ profile: 'home', tools: ['claude', 'kiro'], obsidian: { vault: m.vault }, mcpSynced: ['atlassian', 'github', 'playwright'] }));
  put(join(m.vault, '.claude', 'CLAUDE.md'), 'old');
  put(join(m.vault, '.claude', 'hooks', 'block-private.mjs'), 'old');
  // Kiro's own rules for the work folder, with the old setup's block; a link to the old work/skills/ folder, now gone
  const wsHash = createHash('sha256').update(process.platform === 'win32' ? realpathSync.native(m.work).replace(/\\/g, '/').toLowerCase() : realpathSync.native(m.work)).digest('hex').slice(0, 16);
  const kiroWs = join(m.home, '.kiro', 'workspace-roots', wsHash, 'permissions.yaml');
  put(kiroWs, 'rules:\n  # >>> generated by node _ai/sync.mjs; add your own rules outside this block\n  - {"capability":"all","effect":"allow"}\n  # <<< generated by node _ai/sync.mjs\n');
  const oldSkill = join(m.work, 'skills', 'obsidian');
  mkdirSync(oldSkill, { recursive: true });
  mkdirSync(join(m.home, '.kiro', 'skills'), { recursive: true });
  symlinkSync(oldSkill, join(m.home, '.kiro', 'skills', 'obsidian'), 'junction');
  rmSync(join(m.work, 'skills'), { recursive: true });
  const ownSkill = join(m.root, 'mine');
  mkdirSync(ownSkill);
  symlinkSync(ownSkill, join(m.home, '.kiro', 'skills', 'mine'), 'junction');

  const r = m.run({ vault: undefined });

  // user-level files: the old text is kept in the backup; the old Kiro workspace block is gone, leaving an empty list
  const [stamp] = readdirSync(join(m.work, '.ai', 'backup'));
  assert.equal(read(m.work, '.ai', 'backup', stamp, 'user', '.claude', 'settings.json'), JSON.stringify({ model: 'sonnet', outputStyle: 'Concise', theme: 'dark', permissions: { deny: ['Read(./secret/**)'] } }, null, 4));
  assert.equal(read(kiroWs), 'rules: []\n');
  assert.deepEqual(readdirSync(join(m.home, '.kiro', 'skills')), ['mine'], 'only the broken link into work/ is removed');
  assert.deepEqual(r.tools, ['claude', 'copilot', 'kiro']);
  assert.equal(r.vault, m.vault, 'the vault comes from the old device file');

  // rules: one always-on file for all 3 tools; path rules per tool
  assert.match(read(m.work, 'AGENTS.md'), /^<!-- Generated from AI-Setup\/rules\/always.md[\s\S]*# Always-on rules/);
  assert.equal(read(m.work, 'CLAUDE.md'), '@AGENTS.md\n');
  assert.match(read(m.work, '.claude/rules/sql.md'), /^---\npaths:\n {2}- "\*\*\/\*\.sql"/);
  assert.match(read(m.work, '.github/instructions/python.instructions.md'), /^---\napplyTo: "\*\*\/\*\.py"/);
  assert.match(read(m.work, '.kiro/steering/sql.md'), /inclusion: fileMatch\nfileMatchPattern: "\*\*\/\*\.sql"/);
  assert.ok(!existsSync(join(m.work, '.github/copilot-instructions.md')) && !existsSync(join(m.work, '.kiro/steering/always.md')), 'AGENTS.md is the one always-on file');
  // the user's own AGENTS.md was moved aside, not lost
  const backups = readdirSync(join(m.work, '.ai', 'backup'));
  assert.equal(read(m.work, '.ai', 'backup', backups[0], 'AGENTS.md'), '# my own rules\n');

  // skills: copied to all 3 tools, tests left out; Kiro gets name and description only
  for (const dir of ['.claude/skills', '.github/skills', '.kiro/skills']) {
    assert.ok(existsSync(join(m.work, dir, 'obsidian', 'scripts', 'vault.mjs')), dir);
    assert.ok(!existsSync(join(m.work, dir, 'obsidian', 'scripts', 'vault.test.mjs')), dir);
  }
  assert.match(read(m.work, '.claude/skills/pplan/SKILL.md'), /argument-hint:/);
  assert.doesNotMatch(read(m.work, '.kiro/skills/pplan/SKILL.md').split('---')[1], /argument-hint/);
  assert.match(read(m.work, '.kiro/skills/pplan/SKILL.md'), /Expected input after the slash command: <goal or feature>/);

  // agents: the tier becomes each tool's model; effort where the tool has it
  assert.match(read(m.work, '.claude/agents/tester.md'), /\nmodel: haiku\neffort: medium\ntools: "Read, Grep, Glob, Bash, PowerShell"\n/);
  assert.match(read(m.work, '.github/agents/reviewer.agent.md'), /\nmodel: "Claude Sonnet 5\.5 \(copilot\)"\nreasoning-effort: high\n/);
  const kiroAgent = readJson(m.work, '.kiro/agents/challenger.json');
  assert.equal(kiroAgent.model, 'claude-opus-5.5');
  assert.equal(kiroAgent.hooks[0].action.command, 'node .ai/hooks/kiro/hook.mjs');
  assert.ok(!('effort' in kiroAgent));

  // hooks: one guard, a loader per tool
  for (const f of ['.ai/hooks/guard.mjs', '.ai/hooks/claude/hook.mjs', '.ai/hooks/copilot/hook.mjs', '.ai/hooks/kiro/hook.mjs', '.ai/templates/common/docs/ai/context.md']) assert.ok(existsSync(join(m.work, f)), f);
  assert.equal(readJson(m.work, '.github/hooks/guard.json').hooks.preToolUse[0].timeoutSec, 10);
  assert.equal(readJson(m.work, '.kiro/hooks/guard.json').hooks[0].trigger, 'PreToolUse');

  // ~/.claude/settings.json: auto mode, the hook, built-ins off; the user's keys and indent stay
  const claudeText = read(m.home, '.claude', 'settings.json');
  const claude = JSON.parse(claudeText);
  assert.match(claudeText, /^\{\n {4}"/);
  assert.equal(claude.permissions.defaultMode, 'auto');
  assert.equal(claude.autoMemoryEnabled, false);
  assert.ok(!('outputStyle' in claude));
  assert.equal(claude.theme, 'dark');
  assert.equal(claude.model, 'sonnet', 'a model the user picked stays');
  assert.ok(claude.permissions.deny.includes('Read(./secret/**)') && claude.permissions.deny.includes('Read(**/*.mdenc)'));
  assert.ok(claude.hooks.PreToolUse[0].hooks[0].args[0].endsWith('/.ai/hooks/claude/hook.mjs'));

  // VS Code: hooks on, Claude's files off for Copilot, memory off, never-auto-approve rules next to the user's
  const vs = readJson(m.vscodeUser, 'settings.json');
  assert.equal(vs['chat.useHooks'], true);
  assert.equal(vs['chat.useClaudeHooks'], false);
  assert.equal(vs['chat.agentSkillsLocations']['.claude/skills'], false);
  assert.equal(vs['chat.copilot.memory.local.enabled'], false);
  assert.equal(vs['chat.tools.terminal.autoApprove']['/^npm test$/'], true);
  assert.equal(vs['chat.tools.edits.autoApprove']['**/*.mdenc'], false);
  assert.equal(vs['workbench.colorTheme'], 'Dark+');

  // Kiro: the old block and its vault rules are gone, the user's rule stays, ours are added once
  const kiro = read(m.home, '.kiro', 'settings', 'permissions.yaml');
  assert.doesNotMatch(kiro, /generated by node _ai|Personal\/\*\*/);
  assert.match(kiro, /- capability: shell\n {4}effect: allow/);
  assert.match(kiro, /"\*\*\/\*\.mdenc"/);

  // MCP: Atlassian added, the retired servers gone, local ones kept
  const mcp = readJson(m.work, '.mcp.json').mcpServers;
  assert.deepEqual(Object.keys(mcp).sort(), ['atlassian', 'mlflow']);
  assert.deepEqual(mcp.atlassian.tools, ['*']);
  assert.ok(!('type' in readJson(m.work, '.kiro/settings/mcp.json').mcpServers.atlassian));
  assert.deepEqual(Object.keys(readJson(m.work, '.vscode/mcp.json').servers), ['mine']);

  // the old setup's leftovers that would undo auto mode or double-fire hooks
  assert.ok(!existsSync(join(m.work, '.claude', 'settings.local.json')));
  assert.ok(!existsSync(join(m.vault, '.claude')));

  // the device file: machine facts and manifest, the old keys kept
  const device = readJson(m.work, '.ai-device.json');
  assert.equal(device.vault, m.vault);
  assert.deepEqual(device.projects, ['Shop']);
  assert.equal(device.profile, 'home');
  assert.deepEqual(device.mcpSynced, ['atlassian']);
  assert.ok(device.manifest.files.includes('.claude/skills/review/SKILL.md'));
  assert.ok(m.work && read(m.work, '.ignore').includes('/AI-Setup/'));

  // a second run changes nothing, also from a shell that spells the path in lower case (Windows paths ignore case)
  const again = m.run();
  assert.deepEqual(again.changes, []);
  const lower = (p) => (process.platform === 'win32' ? p.toLowerCase() : p);
  assert.deepEqual(m.run({ work: lower(m.work), home: lower(m.home), vault: lower(m.vault), repo: lower(m.repo) }).changes, []);
});

test('the main model is set when none is, and a later /model choice is kept', () => {
  const m = machine();
  const file = join(m.home, '.claude', 'settings.json');
  m.run();
  assert.equal(readJson(file).model, 'opus');
  // built-in agents that name no model run on the balanced tier, not on the main model
  assert.equal(readJson(file).env.CLAUDE_CODE_SUBAGENT_MODEL, 'sonnet');
  put(file, JSON.stringify({ ...readJson(file), model: 'sonnet' }, null, 2) + '\n');
  m.run();
  assert.equal(readJson(file).model, 'sonnet');
  m.setSetup((s) => { s.models.deep.claude = 'opus[1m]'; });
  m.run();
  assert.equal(readJson(file).model, 'sonnet', 'a model upgrade does not override the user');
  m.setSetup((s) => { s.tools.claude = false; });
  m.run();
  assert.ok(!('env' in readJson(file)), 'Claude turned off removes the built-in agent model');
});

test('VS Code settings with comments are merged in place: comments stay, a second run changes nothing, off removes our keys', () => {
  const m = machine();
  const file = join(m.vscodeUser, 'settings.json');
  const mine = '{\n    // my theme\n    "workbench.colorTheme": "Dark+", /* keep */\n    "chat.useHooks": false,\n    "editor.fontSize": 14,\n}\n';
  put(file, mine);
  m.run();
  const text = read(file);
  assert.match(text, /\/\/ my theme\n {4}"workbench\.colorTheme": "Dark\+", \/\* keep \*\//);
  const parsed = JSON.parse(blankJsonc(text));
  assert.equal(parsed['chat.useHooks'], true);
  assert.equal(parsed['editor.fontSize'], 14);
  assert.equal(parsed['chat.tools.edits.autoApprove']['**/*.mdenc'], false);
  assert.deepEqual(m.run().changes, []);
  m.setSetup((s) => { s.tools.copilot = false; });
  m.run();
  const off = read(file);
  assert.match(off, /\/\/ my theme/);
  assert.deepEqual(Object.keys(JSON.parse(blankJsonc(off))).sort(), ['editor.fontSize', 'workbench.colorTheme']);
  assert.equal(editJsonc('{}', {}, { a: 1 }), '{\n  "a": 1\n}');
});

